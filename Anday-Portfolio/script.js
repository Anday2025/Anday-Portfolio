// Track the section immediately below the sticky header, in either scroll direction.
const navigationLinks = [...document.querySelectorAll('#navigation a')];

function setActiveNavigation(id) {
  navigationLinks.forEach((link) => {
    const active = new URL(link.href, window.location.href).hash === `#${id}`;
    link.classList.toggle('is-active', active);
    if (active) {
      link.setAttribute('aria-current', 'location');
    } else {
      link.removeAttribute('aria-current');
    }
  });
}

if (document.querySelector('main.detail')) {
  setActiveNavigation('projects');
} else {
  const navigationSections = navigationLinks
    .map((link) => document.getElementById(new URL(link.href).hash.slice(1)))
    .filter(Boolean);

  if (navigationSections.length) {
    let navigationFramePending = false;

    function updateActiveNavigation() {
      navigationFramePending = false;
      const activationLine =
        document.querySelector('header').getBoundingClientRect().bottom + 24;
      let currentSection = navigationSections[0];
      navigationSections.forEach((section) => {
        if (section.getBoundingClientRect().top <= activationLine) {
          currentSection = section;
        }
      });
      // The short contact section may never reach the activation line at page end.
      if (
        window.scrollY > 0 &&
        window.scrollY + window.innerHeight >=
          document.documentElement.scrollHeight - 2
      ) {
        currentSection = navigationSections[navigationSections.length - 1];
      }
      setActiveNavigation(currentSection.id);
    }

    function scheduleNavigationUpdate() {
      if (!navigationFramePending) {
        navigationFramePending = true;
        window.requestAnimationFrame(updateActiveNavigation);
      }
    }

    window.addEventListener('scroll', scheduleNavigationUpdate, { passive: true });
    window.addEventListener('resize', scheduleNavigationUpdate);
    window.addEventListener('hashchange', scheduleNavigationUpdate);
    window.addEventListener('load', scheduleNavigationUpdate);
    const navigationResizeObserver = new ResizeObserver(scheduleNavigationUpdate);
    navigationResizeObserver.observe(document.querySelector('header'));
    navigationSections.forEach((section) => navigationResizeObserver.observe(section));
    updateActiveNavigation();
  }
}

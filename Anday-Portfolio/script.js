function setLanguage(language) {
  const lang = language === 'en' ? 'en' : 'no';
  document.documentElement.lang = lang;
  document.querySelectorAll('[data-i18n]').forEach((el) => {
    el.textContent = translations[lang][el.dataset.i18n];
  });
  document
    .querySelectorAll('[data-i18n-alt]')
    .forEach((el) => el.setAttribute('alt', translations[lang][el.dataset.i18nAlt]));
  document
    .querySelectorAll('[data-i18n-aria]')
    .forEach((el) =>
      el.setAttribute('aria-label', translations[lang][el.dataset.i18nAria]),
    );
  document
    .querySelectorAll('[data-lang]')
    .forEach((el) => el.setAttribute('aria-pressed', String(el.dataset.lang === lang)));
  document
    .querySelector('nav')
    .setAttribute('aria-label', lang === 'en' ? 'Main navigation' : 'Hovedmeny');
  try {
    localStorage.setItem('anday-language', lang);
  } catch {}
}
